func TestUpstreamV1735SchemaAndMigrationReplay(t *testing.T) {
	var db *gorm.DB
	if os.Getenv("CANVAS_TEST_MIGRATION_DRIVER") == "postgres" {
		db = isolatedMigrationDB(t)
	} else {
		var err error
		db, err = gorm.Open(sqlite.Dialector{DriverName: "sqlite", DSN: filepath.Join(t.TempDir(), "migration.db")}, &gorm.Config{})
		if err != nil {
			t.Fatal(err)
		}
		sqlDB, err := db.DB()
		if err != nil {
			t.Fatal(err)
		}
		t.Cleanup(func() { _ = sqlDB.Close() })
	}
	if err := MigrateSchema(db); err != nil {
		t.Fatal(err)
	}
	user := model.User{ID: "local-referral-user", Username: "local-referral-user", Role: model.UserRoleUser, Status: model.UserStatusActive}
	profile := model.ReferralProfile{UserID: user.ID, Code: "AB2345", Paused: true}
	if err := db.Create(&user).Error; err != nil {
		t.Fatal(err)
	}
	if err := db.Create(&profile).Error; err != nil {
		t.Fatal(err)
	}
	var before []schemaMigration
	if err := db.Order("version").Find(&before).Error; err != nil {
		t.Fatal(err)
	}
	if int64(len(before)) != CurrentSchemaVersion || before[94].Name != "official_inspiration_catalog" || before[95].Name != "versioned_referral_policies" || before[98].Name != "user_groups_channel_access" || before[102].Name != "ecommerce_agent_and_knowledge" {
		t.Fatalf("unexpected local migration identities: %+v", before)
	}
	for range 2 {
		if err := MigrateSchema(db); err != nil {
			t.Fatal(err)
		}
	}
	var after []schemaMigration
	if err := db.Order("version").Find(&after).Error; err != nil {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(before, after) {
		t.Fatal("replay changed migration ledger")
	}
	var restored model.ReferralProfile
	if err := db.First(&restored, "user_id = ?", user.ID).Error; err != nil {
		t.Fatal(err)
	}
	if restored.Code != profile.Code || !restored.Paused {
		t.Fatalf("local referral controls changed: %+v", restored)
	}
	if !db.Migrator().HasTable(&model.ReferralReward{}) {
		t.Fatal("local referral rewards are missing")
	}
	for _, name := range []string{"referral_bindings", "referral_commissions"} {
		if db.Migrator().HasTable(name) {
			t.Fatalf("duplicate referral table %s was created", name)
		}
	}
	for _, item := range []struct {
		table  string
		column string
	}{
		{"channel_models", "price_currency"}, {"topup_products", "currency"},
		{"billing_orders", "currency_rate_microcredits"}, {"user_groups", "ratio_basis_points"},
		{"user_groups", "points_per_usd"}, {"user_groups", "points_per_cny"},
	} {
		if db.Migrator().HasColumn(item.table, item.column) {
			t.Fatalf("excluded pricing column %s.%s was created", item.table, item.column)
		}
	}
	for _, item := range []any{&model.User{}, &model.BillingOrder{}} {
		if !db.Migrator().HasColumn(item, "UserGroup") {
			t.Fatalf("missing group column on %T", item)
		}
	}
	if !db.Migrator().HasTable(&model.AgentMemoryDocument{}) || !db.Migrator().HasTable(&model.AgentMemoryDocumentRevision{}) {
		t.Fatal("official Agent memory tables are missing")
	}
}

func TestUpstreamV1735UpgradeHistorical96(t *testing.T) {
	var db *gorm.DB
	var err error
	if dsn := os.Getenv("CANVAS_TEST_BASELINE96_DSN"); dsn != "" {
		db, err = gorm.Open(postgres.Open(dsn), &gorm.Config{})
	} else if source := os.Getenv("CANVAS_TEST_BASELINE96_PATH"); source != "" {
		data, readErr := os.ReadFile(source)
		if readErr != nil {
			t.Fatal(readErr)
		}
		path := filepath.Join(t.TempDir(), "historical96.db")
		if err := os.WriteFile(path, data, 0600); err != nil {
			t.Fatal(err)
		}
		db, err = gorm.Open(sqlite.Dialector{DriverName: "sqlite", DSN: path}, &gorm.Config{})
	} else {
		t.Skip("requires a temporary schema 96 fixture generated by commit 28089ad0")
	}
	if err != nil {
		t.Fatal(err)
	}
	sqlDB, err := db.DB()
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = sqlDB.Close() })
	var before []schemaMigration
	if err := db.Order("version").Find(&before).Error; err != nil {
		t.Fatal(err)
	}
	if len(before) != 96 || before[95].Name != "versioned_referral_policies" {
		t.Fatalf("not a historical local 96 ledger: %+v", before)
	}
	if db.Migrator().HasColumn(&model.User{}, "UserGroup") || db.Migrator().HasTable(&model.AgentMemoryDocument{}) {
		t.Fatal("fixture already contains the new schema")
	}
	var accountBefore model.CreditAccount
	var profileBefore model.ReferralProfile
	if err := db.First(&accountBefore, "user_id = ?", "baseline96-user").Error; err != nil {
		t.Fatal(err)
	}
	if err := db.First(&profileBefore, "user_id = ?", "baseline96-user").Error; err != nil {
		t.Fatal(err)
	}
	for range 3 {
		if err := MigrateSchema(db); err != nil {
			t.Fatal(err)
		}
	}
	var after []schemaMigration
	if err := db.Order("version").Find(&after).Error; err != nil {
		t.Fatal(err)
	}
	if len(after) != 103 || !reflect.DeepEqual(before, after[:96]) {
		t.Fatal("upgrade changed the historical ledger")
	}
	var accountAfter model.CreditAccount
	var profileAfter model.ReferralProfile
	if err := db.First(&accountAfter, "user_id = ?", "baseline96-user").Error; err != nil {
		t.Fatal(err)
	}
	if err := db.First(&profileAfter, "user_id = ?", "baseline96-user").Error; err != nil {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(accountBefore, accountAfter) || !reflect.DeepEqual(profileBefore, profileAfter) {
		t.Fatal("upgrade changed local credit or referral data")
	}
	if !db.Migrator().HasColumn(&model.User{}, "UserGroup") || !db.Migrator().HasTable(&model.AgentMemoryDocument{}) {
		t.Fatal("upgrade did not add group and memory schema")
	}
}
